export const SCANNER_LANGS = { fr, es, nl, pl, tr, uk, ru } as const
export type Lang = FullLang | keyof typeof SCANNER_LANGS

// Native names, in the order shown in the language picker: full languages first.
export const LANG_NAMES: Record<Lang, string> = {
  de: 'Deutsch',
  en: 'English',
  it: 'Italiano',
  fr: 'Français',
  es: 'Español',
  nl: 'Nederlands',
  pl: 'Polski',
  tr: 'Türkçe',
  uk: 'Українська',
  ru: 'Русский',
}

const isLang = (s: string): s is Lang => s in LANGS || s in SCANNER_LANGS
const dict = (l: Lang): Partial<Dict> => (l in LANGS ? LANGS[l as FullLang] : SCANNER_LANGS[l as keyof typeof SCANNER_LANGS])

const STORAGE_KEY = 'parkzettel.lang'

// Landing pages have one URL per full language (/de/, /en/, /it/) for search engines. The path wins over any
// saved choice so the page matches what was indexed, and is saved so /create and /account keep it.
export function pathLang(path: string): FullLang | undefined {
  const l = path.match(/^\/([a-z]{2})\/?$/)?.[1]
  return l && l in LANGS ? (l as FullLang) : undefined
}

function detect(): Lang {
  // vite.config.ts imports this module in Node to prerender the landing page; there is no browser state.
  if (typeof window === 'undefined') return 'en'
  const fromPath = pathLang(location.pathname)
  try {
    if (fromPath) {
      localStorage.setItem(STORAGE_KEY, fromPath)
      return fromPath
    }
    const saved = localStorage.getItem(STORAGE_KEY)
    if (saved && isLang(saved)) return saved
  } catch {}
  if (fromPath) return fromPath
  for (const l of navigator.languages ?? [navigator.language]) {
    const base = l.slice(0, 2).toLowerCase()
    if (isLang(base)) return base
  }
  return 'en'
}

let current: Lang = detect()
const listeners = new Set<() => void>()

export const lang = () => current

// Lookup in a given language, without the page state; the build-time prerender uses it.
export function tIn(l: Lang, key: Key, vars: Record<string, string> = {}): string {
  return (dict(l)[key] ?? en[key]).replace(/\{(\w+)\}/g, (_, k) => vars[k] ?? '')
}

export const t = (key: Key, vars: Record<string, string> = {}) => tIn(current, key, vars)

export function setLang(l: Lang) {
  current = l
  try {
    localStorage.setItem(STORAGE_KEY, l)
  } catch {}
  document.documentElement.lang = l
  listeners.forEach((fn) => fn())
}

export function onLangChange(fn: () => void) {
  listeners.add(fn)
}

// Fills every [data-i18n] / [data-i18n-ph] / [data-i18n-label] element under root.
export function translate(root: ParentNode) {
  root.querySelectorAll<HTMLElement>('[data-i18n]').forEach((el) => {
    el.textContent = t(el.dataset.i18n as Key)
  })
  root.querySelectorAll<HTMLInputElement>('[data-i18n-ph]').forEach((el) => {
    el.placeholder = t(el.dataset.i18nPh as Key)
  })
  root.querySelectorAll<HTMLElement>('[data-i18n-label]').forEach((el) => {
    el.setAttribute('aria-label', t(el.dataset.i18nLabel as Key))
  })
}
